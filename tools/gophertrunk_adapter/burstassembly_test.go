func testBurst(index int, rf int) inputPacket {
	return inputPacket{Burst: &index, RFBaseIdx: fmt.Sprint(rf), Cadence: 288,
		AMBE49: []string{"01020304050680", "01020304050680", "01020304050680"}}
}

func TestBurstAssemblyDoesNotStitchMissingFrames(t *testing.T) {
	var a burstAssembly
	dibits := make([]uint8, 132)
	for _, burst := range []int{2, 3, 4, 5} {
		if complete, _ := a.Push(testBurst(burst, burst*288), dibits, burst*132); complete {
			t.Fatal("mid-superframe input was accepted")
		}
	}
	for burst := 0; burst < 6; burst++ {
		complete, lost := a.Push(testBurst(burst, 2000+burst*288), dibits, 1000+burst*132)
		if lost || complete != (burst == 5) {
			t.Fatalf("burst %d: complete=%v lost=%v", burst, complete, lost)
		}
	}
	if len(a.Dibits) != 792 || len(a.Corrected) != 18 || a.Base != 1000 {
		t.Fatal("bad complete frame")
	}
	a.Reset()
	a.Push(testBurst(0, 0), dibits, 0)
	if complete, lost := a.Push(testBurst(2, 576), dibits, 132); complete || !lost || a.Active() {
		t.Fatal("missing B was silently removed")
	}
	a.Push(testBurst(0, 2000), dibits, 1000)
	if complete, lost := a.Push(testBurst(1, 2576), dibits, 1132); complete || !lost {
		t.Fatal("RF gap ignored")
	}
}

func TestARC4SuperframeLFSRAndFrameConsumption(t *testing.T) {
	if dmrArc4NextMI(0x12345678) != 0xb468e067 || dmrArc4NextMI(0x3930d1b1) != 0x72b63d29 {
		t.Fatal("MI advanced by less than 32 recurrence bits")
	}
	p := newPrivacyState()
	p.Configure(privacyConfig{Mode: "arc4", KeyID: 1, KeyHex: "0102030405"})
	if ok, reason := p.UpdatePIHeader(piHeaderInfo{ALG: 1, KeyID: 1, MI: "12345678"}, 0); !ok {
		t.Fatal(reason)
	}
	for frame := 0; frame < 38; frame++ {
		mi := dmrArc4AdvanceMI(0x12345678, frame/18)
		c, _ := stdrc4.NewCipher([]byte{1, 2, 3, 4, 5, byte(mi >> 24), byte(mi >> 16), byte(mi >> 8), byte(mi)})
		discarded := make([]byte, 256+(frame%18)*7)
		c.XORKeyStream(discarded, discarded)
		plain := []byte{0x82, 0x7e, 0x93, 0xd4, 0x85, 0x76, 0x80}
		encrypted := append([]byte(nil), plain...)
		c.XORKeyStream(encrypted, encrypted)
		if frame == 7 {
			p.SkipVoiceFrame()
			continue
		}
		bits := make([]byte, 49)
		unpackBitsInto(encrypted, bits)
		if !p.ApplyBits(bits) || !bytes.Equal(packBits(bits), plain) {
			t.Fatalf("frame %d not decrypted/aligned", frame)
		}
		p.MarkVoiceFrameSeen()
	}
	if p.voiceFrames != 38 || p.totalFrames != 37 {
		t.Fatal("voice counted twice")
	}
}

func lateEntryFrames(mi uint32) [18][]byte {
	var miBits [32]byte
	for bit := range miBits {
		miBits[bit] = byte((mi >> uint(31-bit)) & 1)
	}
	value := uint64(mi)<<4 | uint64(dmrCRC4(miBits[:]))
	var nibbles [6][3]byte
	for frame := 0; frame < 3; frame++ {
		data := uint16((value >> uint(24-frame*12)) & 0xfff)
		word := dmrGolayEncode(data)
		for burst := 0; burst < 3; burst++ {
			nibbles[burst][frame] = byte(data>>uint(8-burst*4)) & 15
			nibbles[burst+3][frame] = byte(word>>uint(8-burst*4)) & 15
		}
	}
	var frames [18][]byte
	for burst := 0; burst < 6; burst++ {
		for frame := 0; frame < 3; frame++ {
			raw := make([]byte, 72)
			for i := 0; i < 36; i++ {
				if ambeRY[i] == 3 && ambeRZ[i] < 4 {
					raw[i*2+1] = (nibbles[burst][frame] >> uint(3-ambeRZ[i])) & 1
				}
			}
			frames[burst*3+frame] = raw
		}
	}
	return frames
}

func TestVerifiedChangingLateEntryDoesNotWaitForIdenticalMI(t *testing.T) {
	p := newPrivacyState()
	p.Configure(privacyConfig{Mode: "arc4", KeyHex: "0102030405"})
	for _, mi := range []uint32{0x12345678, 0xb468e067} {
		frames := lateEntryFrames(mi)
		p.UpdateLateEntry(frames)
		if !p.lateCRCOk || p.lateMI != mi {
			t.Fatalf("verified MI %08X not acquired: %+v", mi, p.Summary(0))
		}
	}
}

func TestDMRGolayWireConvention(t *testing.T) {
	// Fixed systematic wire words, not generated by the decoder under test.
	for data, word := range map[uint16]uint32{0x800: 0x800c75, 1: 0x0018eb, 0x400: 0x40063b} {
		if dmrGolayEncode(data) != word {
			t.Fatalf("wire word for %03X", data)
		}
		if got, errors := dmrGolayDecode(word ^ 0x100081); got != data || errors != 3 {
			t.Fatalf("three-bit correction: data=%03X errors=%d", got, errors)
		}
	}
	for data := 1; data < 4096; data++ {
		if bits.OnesCount32(dmrGolayWords[data]) < 8 {
			t.Fatal("invalid minimum code distance")
		}
	}
}

func TestCorrectedPayloadNotDecodedTwice(t *testing.T) {
	p := newPrivacyState()
	p.Configure(privacyConfig{Mode: "arc4", KeyID: 1, KeyHex: "0102030405"})
	p.UpdatePIHeader(piHeaderInfo{ALG: 1, KeyID: 1, MI: "12345678"}, 0)
	var sf dmrvoice.VoiceSuperframe
	corrected := make([]string, 18)
	for i := range sf.Frames {
		sf.Frames[i] = make([]byte, 72)
		corrected[i] = "827E93D4857680"
	}
	out := summarizeSuperframe(sf, nil, nil, p, 1, "input", nil, corrected)
	if p.voiceFrames != 18 || p.rc4FrameIndex != 18 || out.Frames != 18 {
		t.Fatal("duplicate AMBE advancement")
	}
}

type captureVocoder struct{ payloads [][]byte }

func (v *captureVocoder) Name() string   { return "test" }
func (v *captureVocoder) FrameSize() int { return 7 }
func (v *captureVocoder) Decode(frame []byte) ([]int16, error) {
	v.payloads = append(v.payloads, append([]byte(nil), frame...))
	return nil, nil
}
func (v *captureVocoder) Reset()       {}
func (v *captureVocoder) Close() error { return nil }

func encryptedSuperframe(mi uint32) []string {
	corrected := make([]string, 18)
	for frame := range corrected {
		c, _ := stdrc4.NewCipher([]byte{1, 2, 3, 4, 5, byte(mi >> 24), byte(mi >> 16), byte(mi >> 8), byte(mi)})
		discarded := make([]byte, 256+frame*7)
		c.XORKeyStream(discarded, discarded)
		payload := []byte{0x82, 0x7e, 0x93, 0xd4, 0x85, 0x76, 0x80}
		c.XORKeyStream(payload, payload)
		payload[6] &= 0x80
		corrected[frame] = fmt.Sprintf("%X", payload)
	}
	return corrected
}

func TestLateEntryAppliesToNextSuperframeNotCurrentVoice(t *testing.T) {
	for _, withPI := range []bool{false, true} {
		p := newPrivacyState()
		p.Configure(privacyConfig{Mode: "arc4", KeyHex: "0102030405"})
		p.UpdateEncryptionState(true)
		const mi = uint32(0x12345678)
		if withPI {
			p.UpdatePIHeader(piHeaderInfo{ALG: 1, MI: "12345678"}, 0)
		}
		voc := &captureVocoder{}
		conn, peer := net.Pipe()
		defer conn.Close()
		defer peer.Close()
		for index := 0; index < 3; index++ {
			current := dmrArc4AdvanceMI(mi, index)
			sf := dmrvoice.VoiceSuperframe{Frames: lateEntryFrames(dmrArc4NextMI(current))}
			before := len(voc.payloads)
			out := summarizeSuperframe(sf, voc, conn, p, 1, "input", nil, encryptedSuperframe(current))
			want := 18
			if index == 0 && !withPI {
				want = 0
			}
			if len(voc.payloads)-before != want {
				t.Fatalf("PI=%v sf=%d: expected %d frames", withPI, index, want)
			}
			if out.Privacy == nil || out.Privacy.NextMI != fmt.Sprintf("%08X", dmrArc4NextMI(current)) {
				t.Fatal("next MI is not identified separately")
			}
			if want == 0 {
				if !out.Privacy.Muted || out.Privacy.Applied {
					t.Fatal("late-entry acquisition hides current superframe mute")
				}
			} else if out.Privacy.VoiceMI != fmt.Sprintf("%08X", current) || !out.Privacy.Applied {
				t.Fatal("voice MI does not describe the frames just decoded")
			}
		}
		for index, payload := range voc.payloads {
			if !bytes.Equal(payload, []byte{0x82, 0x7e, 0x93, 0xd4, 0x85, 0x76, 0x80}) {
				t.Fatalf("PI=%v frame=%d: MI applied one superframe too early", withPI, index)
			}
		}
	}
}

