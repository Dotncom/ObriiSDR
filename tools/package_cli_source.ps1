# The standalone CLI links the Mesh node service and its protocol modules.
$meshFiles = @(git -C $root ls-files --cached --others --exclude-standard -- src/mesh src/lora src/meshtastic src/lorawan)
if ($LASTEXITCODE -ne 0 -or $meshFiles.Count -eq 0) { throw 'Unable to enumerate CLI Mesh sources.' }
$files += @($meshFiles | Where-Object { $_ -match '(?:\.(?:c|cpp|h|hpp|md)$|/(?:CMakeLists\.txt|NOTICE|LICENSE)$)' })

foreach ($relativePath in $files) {
    $fullPath = Join-Path $root $relativePath
    if (-not (Test-Path -LiteralPath $fullPath -PathType Leaf)) {
        throw "Missing CLI source file: $relativePath"
    }
}

Assert-ObriiPublicPackageFiles -Root $root -Paths $files

Add-Type -AssemblyName System.IO.Compression
Add-Type -AssemblyName System.IO.Compression.FileSystem
$parent = Split-Path -Parent $destinationPath
[System.IO.Directory]::CreateDirectory($parent) | Out-Null
$file = [System.IO.File]::Open($destinationPath, [System.IO.FileMode]::Create,
                              [System.IO.FileAccess]::Write, [System.IO.FileShare]::None)
try {
    $archive = [System.IO.Compression.ZipArchive]::new($file, [System.IO.Compression.ZipArchiveMode]::Create)
    try {
        foreach ($relativePath in $files) {
            $fullPath = Join-Path $root $relativePath
            $entryName = $relativePath.Replace('\', '/')
            [System.IO.Compression.ZipFileExtensions]::CreateEntryFromFile(
                $archive, $fullPath, $entryName,
                [System.IO.Compression.CompressionLevel]::Optimal) | Out-Null
        }
    } finally {
        $archive.Dispose()
    }
} finally {
    $file.Dispose()
}
Assert-ObriiPublicZip -Path $destinationPath
Write-Host "CLI source archive: $destinationPath"
